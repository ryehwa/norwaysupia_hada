-- 알림 발송 추적(notified_at) 기능을 배포할 때 한 번만 실행한다.
--
-- ddl-auto: update 는 컬럼만 만들고 값은 채우지 않으므로, 기존 문의가 전부
-- notified_at = NULL(미발송) 상태가 된다. 그대로 두면 스케줄러가 과거 문의
-- 전체에 대해 알림을 다시 보낸다.
--
-- 실행 시점: 애플리케이션이 새 스키마로 한 번 뜬 뒤(컬럼 생성됨), 첫 스케줄러
-- 실행(기동 60초 후) 전. 안전하게는 백엔드를 내린 상태에서 실행한다.
--
-- 코드에도 7일 안전장치가 있어 이 스크립트를 빠뜨려도 사고는 나지 않지만,
-- 최근 7일 문의는 재발송되므로 실행하는 편이 깔끔하다.

UPDATE inquiries
   SET notified_at = submitted_at
 WHERE notified_at IS NULL;
